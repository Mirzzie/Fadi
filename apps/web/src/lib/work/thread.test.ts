import type { AgentMessage, WorkExecution, WorkItem, WorkOutput } from "@careeros/database";
import { describe, expect, it } from "vitest";

import { projectWorkThread } from "./thread";

const at = (value: string) => new Date(value);
const item = {
  id: "work-1",
  userId: "user-1",
  careerProfileId: null,
  parentId: null,
  kind: "step",
  title: "Check Wazuh alerts",
  detail: "Inspect the alert generated by the lab.",
  status: "blocked",
  reason: "The result is still unknown.",
  refs: [],
  dueAt: null,
  completedAt: null,
  sortOrder: 0,
  createdAt: at("2026-10-16T18:00:00Z"),
  updatedAt: at("2026-10-16T18:04:00Z"),
} as WorkItem;

describe("work thread projection", () => {
  it("puts conversation, execution, output and current work state in one ordered narrative", () => {
    const events = projectWorkThread({
      item,
      messages: [
        {
          id: "message-1",
          userId: "user-1",
          role: "user",
          content: "Check whether the alert arrived.",
          contextSummary: null,
          workItemId: item.id,
          metadata: {},
          createdAt: at("2026-10-16T18:01:00Z"),
          updatedAt: at("2026-10-16T18:01:00Z"),
        } as AgentMessage,
      ],
      executions: [
        {
          id: "execution-1",
          userId: "user-1",
          workItemId: item.id,
          workLabel: item.title,
          action: "Query Wazuh indexer",
          surface: "web",
          risk: "read",
          status: "failed",
          receipt: "",
          error: "The indexer did not answer.",
          approvalId: null,
          startedAt: at("2026-10-16T18:02:00Z"),
          finishedAt: at("2026-10-16T18:03:00Z"),
          createdAt: at("2026-10-16T18:02:00Z"),
          updatedAt: at("2026-10-16T18:03:00Z"),
          place: "host",
          observer: "tool",
        } as WorkExecution & { place: "host"; observer: "tool" },
      ],
      outputs: [
        {
          id: "output-1",
          userId: "user-1",
          workItemId: item.id,
          kind: "report",
          refId: "report-1",
          label: "Diagnostic report",
          createdAt: at("2026-10-16T18:03:30Z"),
          updatedAt: at("2026-10-16T18:03:30Z"),
        } as WorkOutput,
      ],
    });

    expect(events.map((event) => event.kind)).toEqual(["message", "execution", "output", "work"]);
    expect(events[1]).toMatchObject({ state: "failed", place: "host", observer: "tool" });
    expect(events[2].ref).toEqual({ type: "report", id: "report-1" });
    expect(events[3]).toMatchObject({ state: "blocked", detail: "The result is still unknown." });
  });

  it("keeps unknown distinct from failed", () => {
    const events = projectWorkThread({
      item: { ...item, status: "future_status" } as WorkItem,
      executions: [
        {
          id: "execution-unknown",
          action: "Observe",
          status: "future_status",
          receipt: "No observation was available.",
          error: null,
          startedAt: at("2026-10-16T18:00:00Z"),
          finishedAt: null,
        } as WorkExecution,
      ],
    });
    expect(events.map((event) => event.state)).toEqual(["unknown", "unknown"]);
  });
});
